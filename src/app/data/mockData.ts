// Points balance the current user holds at a specific salon.
export function getSalonPoints(salonId: string): number {
  return currentUser.salonPoints.find((s) => s.salonId === salonId)?.points ?? 0;
}

// Lifetime points across all salons - informational only (e.g. for a loyalty
// tier badge). This is NOT a spendable balance; redemption always checks
// getSalonPoints() for a specific salon instead.
export function getTotalLifetimePoints(): number {
  return currentUser.salonPoints.reduce((sum, s) => sum + s.points, 0);
}

